#!/usr/bin/env python3
"""Turn philolog's notes/nuggets.fr.md into a C header for the e-paper firmware.

    gen_nuggets.py PATH/TO/nuggets.fr.md [-o ../philolog/nuggets.h]

The nuggets live in the private philolog repo, so the generated header is
git-ignored here. Characters outside Latin-1 are replaced, because the u8g2
fonts used on the display only cover Latin-1.
"""
import argparse
import re
import sys
from pathlib import Path

REPLACE = {"œ": "oe", "Œ": "OE", "—": "-", "–": "-", "…": "...",
           "’": "'", "‘": "'", "“": "\"", "”": "\"", " ": " ", " ": " "}


def clean(text):
    for a, b in REPLACE.items():
        text = text.replace(a, b)
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"\*(.+?)\*", r"\1", text)
    text = text.replace("`", "")
    bad = sorted({ch for ch in text if ord(ch) > 255})
    if bad:
        sys.exit(f"characters outside Latin-1: {bad}")
    # Keep French punctuation on the same line as its word when wrapping.
    text = re.sub(r" (?=[?!:;»])", " ", text.strip())
    return text.replace("« ", "« ")


def parse_day(part):
    heading, *lines = part.strip().splitlines()
    number = int(re.match(r"Jour (\d+)", heading).group(1))
    title = re.sub(r"^Jour \d+\s*[—-]\s*", "", heading)

    quote, author, body, essayer, source = [], "", [], "", ""
    for line in lines:
        if line.startswith(">"):
            text = line.lstrip("> ").strip()
            if text.startswith("—"):
                author = text.lstrip("— ").strip()
            elif text:
                quote.append(text)
        elif line.startswith("**À essayer"):
            essayer = re.sub(r"^\*\*À essayer\s*:\*\*\s*", "", line)
        elif line.startswith("*Source"):
            source = re.sub(r"^\*Source\s*:\*\s*", "", line)
            source = re.sub(r"\s*\*Liens\s*:\*.*$", "", source)
        elif line.strip() and not essayer and not source:
            body.append(line.strip())

    day = {"title": title, "quote": " ".join(quote), "author": author,
           "body": " ".join(body), "essayer": essayer, "source": source}
    missing = [k for k, v in day.items() if not v]
    if missing:
        sys.exit(f"Jour {number}: missing {missing}")
    return number, {k: clean(v) for k, v in day.items()}


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("src", type=Path)
    parser.add_argument("-o", "--out", type=Path,
                        default=Path(__file__).resolve().parent.parent / "philolog" / "nuggets.h")
    args = parser.parse_args()

    text = args.src.read_text(encoding="utf-8")
    days = dict(parse_day(p) for p in re.split(r"(?m)^## (?=Jour \d+\b)", text)[1:])
    if sorted(days) != list(range(1, len(days) + 1)):
        sys.exit(f"expected Jour 1..N, found {sorted(days)}")

    out = ["// Generated by tools/gen_nuggets.py from philolog notes/nuggets.fr.md. Do not edit.",
           "#pragma once", "", "struct Nugget {",
           "  const char *title, *quote, *author, *body, *essayer, *source;", "};", "",
           "static const Nugget NUGGETS[] = {"]
    for n in sorted(days):
        d = days[n]
        out.append(f"  {{ // Jour {n}")
        out += [f"    {c_string(d[k])}," for k in ("title", "quote", "author", "body", "essayer", "source")]
        out.append("  },")
    out += ["};", "", "static const int NUGGET_COUNT = sizeof(NUGGETS) / sizeof(NUGGETS[0]);", ""]
    # The firmware draws Latin-1 through u8g2's UTF-8 functions, so keep UTF-8.
    args.out.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {len(days)} nuggets to {args.out}")


if __name__ == "__main__":
    main()
